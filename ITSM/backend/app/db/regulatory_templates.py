def seed_templates(db) -> int:
    """将内置模板写入模板库（幂等：按 (reg_source, title) 去重）。返回新增条数。"""
    from app.models import ComplianceRequirementTemplate

    existing = {
        (t.reg_source, t.title)
        for t in db.query(ComplianceRequirementTemplate).all()
    }
    added = 0
    for i, tpl in enumerate(TEMPLATES):
        if (tpl["reg_source"], tpl["title"]) in existing:
            continue
        db.add(
            ComplianceRequirementTemplate(
                reg_source=tpl["reg_source"],
                domain=tpl["domain"],
                title=tpl["title"],
                clause=tpl["clause"],
                category=tpl["category"],
                sort_order=i,
                is_builtin=True,
            )
        )
        added += 1
    return added
